/** Template related settings. Owned by the notifications page and persisted by its Save button. */
export interface NotificationTemplateSettings {
	templates: Record<string, NotificationTemplate>
	timezone: string
}

interface NotificationTemplatesProps extends NotificationTemplateSettings {
	onChange: (value: NotificationTemplateSettings) => void
}

/** Extracts the template settings from the stored user settings */
export function templateSettingsFromUser(userSettings: UserSettings): NotificationTemplateSettings {
	return {
		templates: userSettings.notificationTemplates ?? {},
		timezone: userSettings.notificationTimezone ?? "",
	}
}

/** Maps the template settings back to the user settings keys */
export function templateSettingsToUser(value: NotificationTemplateSettings): Partial<UserSettings> {
	return {
		notificationTemplates: value.templates,
		notificationTimezone: value.timezone,
	}
}

type TemplateField = "title" | "body"

interface PreviewResponse {
	title: string
	body: string
	err?: string
}

interface KindDef {
	kind: string
	name: () => string
	description: () => string
	/** kind specific placeholders, shown before the common ones */
	vars: string[]
	/** fixed values of {state} for this kind */
	states?: string[]
	/** description of {state} when it is not a fixed list */
	stateHint?: () => string
	/** close template equivalent of the built-in text (the real message is generated by code) */
	builtin: { title: string; body: string }
}

